"""Write migration/MISSING-CONTENT.md from migration/report.json and the recovery's own reports.

Usage: python -I scripts/missing_report.py <recovery_dir> <app_dir>
"""
import json
import os
import sys
from collections import Counter, defaultdict

REC, APP = os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2])
r = json.load(open(os.path.join(APP, "migration", "report.json"), encoding="utf-8"))
redirects = json.load(open(os.path.join(APP, "src", "content", "redirects.json"), encoding="utf-8"))
posts = json.load(open(os.path.join(APP, "src", "content", "posts.json"), encoding="utf-8"))
courses = json.load(open(os.path.join(APP, "src", "content", "courses.json"), encoding="utf-8"))
title = {p["path"]: p["title"] for p in posts}

L = ["# Missing-content report", "",
     "Generated by `scripts/missing_report.py` from `migration/report.json` (written by `scripts/migrate.py`).",
     "Nothing below was replaced with invented text or substitute images.", "",
     "## Summary", "", "| Item | Count |", "|---|---|"]
c = r["counts"]
L += [f"| Content pages migrated | {c['pages']} (+ homepage, services overview, IT Training catalog) |",
      f"| Blog articles migrated | {c['posts']} |",
      f"| Blog categories | {c['categories']} |",
      f"| IT Training courses / course categories | {c['courses']} / {c['courseCategories']} |",
      f"| Images and fonts published to public/assets | {c['assets']} |",
      f"| Pages never recovered from the archive | {len(r['unrecovered_pages'])} |",
      f"| Recovered pages deliberately not migrated | {len(r['excluded_pages'])} |",
      f"| Redirects for recovered URLs whose content moved | {len(redirects)} (+ WooCommerce pages → /shop/) |",
      f"| Image references with no archived file | {len(r['missing_images'])} |",
      f"| Articles without a recovered featured image | {len(r['posts_without_featured_image'])} of {c['posts']} |",
      f"| Courses without a recovered image | {sum(1 for x in courses if not x['image'])} of {c['courses']} |", ""]

L += ["## Pages never recovered", "",
      "Every Wayback Machine capture of these URLs returns 404. The `/blog/page/N/` and course-category pagination URLs exist "
     "again in the new site (regenerated from the migrated articles and courses); the author archives are not rebuilt.", ""]
L += [f"- {u}" for u in r["unrecovered_pages"]]

L += ["", "## Recovered pages not migrated", "", "| Path | Reason |", "|---|---|"]
L += [f"| `{e['path']}` | {e['reason']} |" for e in r["excluded_pages"]]

L += ["", "## Redirects generated from the recovery", "", "| From | To | Why |", "|---|---|---|"]
L += [f"| `{x['source']}` | `{x['destination']}` | {x['reason']} |" for x in redirects]

L += ["", "## Content changes made during reconstruction", "",
      "- **Navigation:** the original menu put the nine services under *Home*; they are now under *Services* (same items and labels). "
      "*Restricted content* (`/free-tools/`, a login wall with no archived content) was removed from the menu.",
      "- **Homepage:** section order follows the 2026-07-11 capture. *Industry Solutions* and *Technology Partners* were added "
      "using text from `/industry/` and `/our-partners/` (they were not on the archived homepage). The archived *Why Choose* "
      "section had only a heading and a *Learn More* button pointing at the homepage itself; the button now opens About Us and "
      "the About Us introduction is shown under the heading.",
      "- **Footer:** *Built by Appzeto* credit omitted (it credits the previous site's developer). The LinkedIn link pointed to the "
      "company-admin dashboard (`/company/91432972/admin/dashboard/`); it now points to the public page `/company/91432972/`.",
      "- **Forms:** Elementor forms are replaced by validated forms with the same fields. Page-specific quotation forms on "
      "MVP Development, Rapid Prototyping, Cybersecurity Access Management and Cybersecurity Assessments had extra questions "
      "(phase, problem definition, target audience, USP, …); they use the standard Get Quote form, whose *Requirement* field "
      "covers those details. Submissions are delivered only when `FORMS_WEBHOOK_URL` is configured.",
      "- **IT Training:** WooCommerce cart/checkout cannot work without the original store; courses show the archived price "
      "and packages with an enquiry button instead. Duplicate course listings that exist twice in the original store keep both URLs "
      "and use a canonical tag.",
      "- **Opening banner headings** of Elementor pages that repeated the page title were dropped "
      f"({len(r.get('banner_titles_dropped', []))} pages); the title is the page H1.", ""]

forms = r.get("forms", [])
if forms:
    L += ["### Original form fields", "", "| Page | Form | Fields in the archive |", "|---|---|---|"]
    L += [f"| `{f['page']}` | {f['kind']} | {f['fields']} |" for f in forms]

L += ["", "## Articles without a featured image", "",
      "The image files were never archived; cards and article headers use a branded panel instead of a substitute photo.", ""]
L += [f"- `{p}` – {title.get(p, '')}" for p in r["posts_without_featured_image"]]

if r.get("thin_posts"):
    L += ["", "## Articles with no recovered body text", ""]
    L += [f"- `{t['path']}` – {title.get(t['path'], '')} ({t['words']} words; featured image only)" for t in r["thin_posts"]]

by_page = defaultdict(list)
for m in r["missing_images"]:
    by_page[m["page"]].append(m["image"])
L += ["", "## Missing images by page", "",
      "Image references in recovered content whose files were never archived (the image is omitted from the page).", "",
      "<details><summary>Show all</summary>", ""]
for page, imgs in sorted(by_page.items()):
    L.append(f"- `{page}`")
    L += [f"  - {i}" for i in sorted(set(imgs))]
L += ["", "</details>"]

skipped = r.get("skipped_widgets", [])
if skipped:
    L += ["", "## Elementor widgets not reproduced", ""]
    L += [f"- `{s['page']}`: {s['widget']}" for s in skipped]

L += ["", "## Unresolved links inside migrated content", "", "Links were removed (text kept) because their target is not part of the site:", ""]
L += [f"- `{u['page']}` → `{u['href']}` ({u['reason']})" for u in r["unresolved_links"]]

L += ["", "## Related recovery reports", "",
      f"- `{os.path.join(REC, 'reports', 'missing-assets.md')}`",
      f"- `{os.path.join(REC, 'reports', 'missing-pages.md')}`",
      f"- `{os.path.join(REC, 'reports', 'verification-report.md')}`", ""]

with open(os.path.join(APP, "migration", "MISSING-CONTENT.md"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(L))
print("wrote migration/MISSING-CONTENT.md", len(L), "lines")
